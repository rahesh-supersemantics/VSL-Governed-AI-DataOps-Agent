"""Regenerate docs/governance-catalogue.md and docs/governance-acceptance-tests.md from the code-side catalogue.
Offline and read-only except for those two files: no database, no network, no model.   python -m scripts.generate_governance_docs"""
from __future__ import annotations

from pathlib import Path

from app.recovery.governance_catalogue import INVARIANTS, PRENODE_SPEC, PRENODES, TRACE
from app.recovery.lifecycle import LOGICAL_STATES, STATE_MAP
from tests.acceptance_map import MAP

ROOT = Path(__file__).resolve().parents[1]
LAYER = {"vsl_gate": "compiled VSL gate", "code": "application code (outside the VSL gates)"}
# logical state -> (allowed preceding, allowed next, trigger, authorisation, audit event, implemented/tested)
FLOW = {
    "Investigating": ("(none)", "Proposed", "investigation requested", "authenticated caller", "(investigation record)", "stored on the investigation; covered by investigation tests, not by recovery transition tests"),
    "Proposed": ("Investigating", "PendingReview, Authorized (policy), Rejected", "proposal validated", "none", "recovery_proposed", "transient, not stored; validation tested (T-06)"),
    "PendingReview": ("Proposed", "Authorized, Rejected, Expired", "approval request created", "none", "approval_requested", "stored; tested (T-03)"),
    "Authorized": ("PendingReview, Proposed (policy)", "Executing, Expired, Rejected (approval invalidated)", "person approves, or policy authorises (low risk, opt-in)", "reviewer with the approval permission, or policy:risk-policy-v1", "approval_granted / approval_granted_by_policy", "derived; tested (T-03, T-17)"),
    "ReadyToExecute": ("Authorized", "Executing", "all pre-execution checks pass", "valid unspent approval", "(none)", "not stored: checks run inside the runner (T-10, T-22)"),
    "Executing": ("Authorized", "Succeeded, Failed, OutcomeUnknown", "atomic claim", "approval consumed once", "recovery_attempt", "stored as resuming; tested (T-09, T-11, T-19)"),
    "Succeeded": ("Executing", "(final)", "postcondition verified", "n/a", "recovery_succeeded", "stored as executed; tested (T-18)"),
    "Failed": ("Executing, Authorized", "Escalated (derived)", "check failed, or postcondition not met", "n/a", "recovery_failed / recovery_verification_failed", "tested (T-10, T-12)"),
    "OutcomeUnknown": ("Executing", "Escalated (derived)", "effect may have happened; result not established", "n/a", "recovery_uncertain", "tested (T-13)"),
    "Rejected": ("PendingReview, Authorized", "(final)", "rejected, cancelled, refused or invalid", "reviewer, or a gate", "approval_rejected / approval_not_usable / recovery_action_rejected", "several stored reasons collapse here; tested (T-02, T-06, T-07, T-09)"),
    "Expired": ("PendingReview, Authorized", "(final)", "approval time-to-live passed", "n/a", "approval_not_usable", "tested (T-10)"),
    "Compensating": ("(none)", "(none)", "not implemented", "would need its own governance", "(none)", "design-only by decision"),
    "Compensated": ("(none)", "(none)", "not implemented", "would need its own governance", "(none)", "design-only by decision"),
    "Escalated": ("Failed, OutcomeUnknown", "(final for automation)", "verification_failed or uncertain", "n/a", "compensation_plan_proposed, recovery_escalated", "derived from the ledger; tested (T-12, T-13)"),
}


def catalogue() -> str:
    o = ["# Governance catalogue: PreNodes, invariants, traceability and lifecycle\n",
         "Generated by `python -m scripts.generate_governance_docs` from `app/recovery/governance_catalogue.py`, `app/recovery/lifecycle.py` and `tests/acceptance_map.py`. "
         "`tests/test_governance_catalogue.py` imports every enforcement symbol, checks every test and ledger outcome exists, and checks every T number is mapped, "
         "so this page cannot name code or tests that are not there.\n",
         "**Honest summary.** The compiled VSL layer has two invariants and one PreNode. The other PreNodes are named stages implemented in ordinary code and are labelled so. "
         "Status values: *enforced* = code stops a violation and an offline test proves it; *partial*; *not_enforced*. Nothing here was run against SQL Server.\n",
         f"Counts: PreNodes enforced {sum(e.status == 'enforced' for e in PRENODES)}, partial {sum(e.status == 'partial' for e in PRENODES)}. "
         f"Invariants enforced {sum(e.status == 'enforced' for e in INVARIANTS)}, partial {sum(e.status == 'partial' for e in INVARIANTS)}, not enforced {sum(e.status == 'not_enforced' for e in INVARIANTS)}.\n",
         "## PreNodes\n"]
    for e in PRENODES:
        purpose, inputs, outputs, events = PRENODE_SPEC[e.id]
        o += [f"### {e.id} - {e.title}\n", f"- **Purpose:** {purpose}", f"- **Inputs:** {inputs}", f"- **Outputs:** {outputs}",
              f"- **Status / layer:** {e.status}; {LAYER[e.layer]}", "- **Enforced at:** " + ", ".join(f"`{x}`" for x in e.enforcement),
              f"- **Rejection behaviour:** {e.failure}", f"- **Audit events:** {events}",
              "- **Tests:** " + ", ".join(f"`{x.split('::')[1]}`" for x in e.tests), f"- **Limitation:** {e.limitation or 'none known'}\n"]
    o.append("## Invariants\n")
    for e in INVARIANTS:
        nodes, events, dash = TRACE[e.id]
        o += [f"### {e.id} - {e.title}\n", f"- **Status / layer:** {e.status}; {LAYER[e.layer]}",
              "- **Enforced at:** " + (", ".join(f"`{x}`" for x in e.enforcement) or "nowhere yet"), f"- **Failure response:** {e.failure}",
              "- **Tests:** " + (", ".join(f"`{x.split('::')[1]}`" for x in e.tests) or "none"), f"- **Limitation:** {e.limitation or 'none known'}\n"]
    o += ["## Traceability matrix\n", "| Invariant | Status | PreNode | Ledger outcome(s) | Dashboard | First test |", "|---|---|---|---|---|---|"]
    for e in INVARIANTS:
        nodes, events, dash = TRACE[e.id]
        o.append(f"| {e.id} | {e.status} | {', '.join(nodes) or '-'} | {', '.join(events) or '-'} | {dash} | {(e.tests[0].split('::')[1] if e.tests else '-')} |")
    o += ["", "## Lifecycle mapping\n", "Implemented in `app/recovery/lifecycle.py` as a read-only mapping; it invents no transition. "
          "The stored status transitions are enforced by the persistence layer (`transition_allowed`, proven by `tests/test_governance_lifecycle.py`): a final row is never reopened or rewritten, and `resuming` is entered only by one atomic claim.\n",
          "| Logical state | Stored as | Exactness | Preceding | Next | Trigger | Authorisation | Audit event | Implemented / tested |", "|---|---|---|---|---|---|---|---|---|"]
    for s in LOGICAL_STATES:
        k, w, n = STATE_MAP[s]
        pre, nxt, trig, auth, ev, impl = FLOW[s]
        o.append(f"| {s} | {w} | {k} | {pre} | {nxt} | {trig} | {auth} | {ev} | {impl} |")
    o += ["", "`direct` = the stored status is this state; `derived` = computed from stored data; `approximate` = closest state, stored reason shown beside it; `not_stored` = the application does not hold it. "
          "Compensating and Compensated are not stored because compensation is design-only by decision.\n",
          "## Acceptance tests (latest numbering)\n", "See `docs/governance-acceptance-tests.md`. T-01 to T-22 are all mapped; T-20 (live model) is pending your approval.\n"]
    return "\n".join(o)


def acceptance() -> str:
    o = ["# Acceptance tests T-01 to T-22 (latest numbering) and where each is proven\n",
         "Generated from `tests/acceptance_map.py` by `python -m scripts.generate_governance_docs`. Function names inside `tests/test_governance_acceptance.py` "
         "use an earlier numbering (`test_tNN_...`); this table is the authority for the latest numbers. A skipped test is not a pass.\n",
         "Common setup: in-memory simulation, fake clock, counting executor, per-test ledger and approval store under a temp directory. "
         "\"No side effect\" means the executor counter and the repository write counter stayed at zero. The expected decision, state transition, side effect and ledger record "
         "of each case are the assertions in the named test.\n",
         "| ID | Criterion | Evidence (tests) | Status |", "|---|---|---|---|"]
    for tid, (title, refs) in MAP.items():
        status = "PENDING approval (skipped, not run)" if "PENDING" in title else "passes offline"
        o.append(f"| {tid} | {title.replace(' (PENDING: needs explicit approval)', '')} | " + "<br>".join(f"`{r.split('/')[-1]}`" for r in refs) + f" | {status} |")
    o.append("")
    return "\n".join(o)


if __name__ == "__main__":
    (ROOT / "docs/governance-catalogue.md").write_text(catalogue(), encoding="utf-8")
    (ROOT / "docs/governance-acceptance-tests.md").write_text(acceptance(), encoding="utf-8")
    print("wrote docs/governance-catalogue.md and docs/governance-acceptance-tests.md")
